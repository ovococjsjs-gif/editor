def paragraph_text(paragraph):
    return ''.join((node.text or '') for node in paragraph.iter(W + 't'))


def clear_runs(paragraph):
    for child in list(paragraph):
        if child.tag != W + 'pPr':
            paragraph.remove(child)


def set_text(paragraph, text):
    clear_runs(paragraph)
    run = ET.SubElement(paragraph, W + 'r')
    node = ET.SubElement(run, W + 't')
    if text.startswith(' ') or text.endswith(' '):
        node.set(XML + 'space', 'preserve')
    node.text = text


def update_core(data):
    root = ET.fromstring(data)
    revision = root.find(CP + 'revision')
    if revision is not None:
        try:
            revision.text = str(int(revision.text or '0') + 1)
        except ValueError:
            pass
    modified = root.find(DCTERMS + 'modified')
    if modified is not None:
        modified.text = datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace('+00:00', 'Z')
    return ET.tostring(root, encoding='utf-8', xml_declaration=True)


def main():
    actual = sha256(SOURCE.read_bytes()).hexdigest()
    if actual != SOURCE_SHA256:
        raise SystemExit(f'Unexpected source hash: {actual}')

    with ZipFile(SOURCE) as zin:
        package = {info.filename: (info, zin.read(info.filename)) for info in zin.infolist()}

    root = ET.fromstring(package['word/document.xml'][1])
    body = root.find(W + 'body')
    if body is None:
        raise SystemExit('DOCX body not found')
    paragraphs = [node for node in list(body) if node.tag == W + 'p']
    if len(paragraphs) != 719 or any(not paragraph_text(p).strip() for p in paragraphs):
        raise SystemExit(f'Expected 719 non-empty paragraphs, got {len(paragraphs)}')

    for index, paragraph in enumerate(paragraphs, 1):
        if index not in EDITS:
            continue
        replacement = EDITS[index]
        if replacement is None:
            body.remove(paragraph)
        elif isinstance(replacement, list):
            set_text(paragraph, replacement[0])
            anchor = list(body).index(paragraph)
            for offset, extra in enumerate(replacement[1:], 1):
                clone = deepcopy(paragraph)
                set_text(clone, extra)
                body.insert(anchor + offset, clone)
        else:
            set_text(paragraph, replacement)

    package['word/document.xml'] = (
        package['word/document.xml'][0],
        ET.tostring(root, encoding='utf-8', xml_declaration=True),
    )
    if 'docProps/core.xml' in package:
        info, data = package['docProps/core.xml']
        package['docProps/core.xml'] = (info, update_core(data))

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(OUTPUT, 'w', ZIP_DEFLATED) as zout:
        for filename, (info, data) in package.items():
            zout.writestr(info, data)
    print(OUTPUT)


if __name__ == '__main__':
    main()
