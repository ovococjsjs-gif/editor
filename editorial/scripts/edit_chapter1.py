# Blank paragraphs create visual breathing without a visible scene-break glyph.
BLANK_BEFORE = {204, 439, 723, 811}


def paragraph_text(paragraph):
    return ''.join((node.text or '') for node in paragraph.iter(W + 't'))


def clear_runs(paragraph):
    for child in list(paragraph):
        if child.tag != W + 'pPr':
            paragraph.remove(child)


def add_text_run(paragraph, text, underline=False, line_break=False):
    run = ET.SubElement(paragraph, W + 'r')
    if underline:
        rpr = ET.SubElement(run, W + 'rPr')
        underline_node = ET.SubElement(rpr, W + 'u')
        underline_node.set(W + 'val', 'single')
    if line_break:
        ET.SubElement(run, W + 'br')
    text_node = ET.SubElement(run, W + 't')
    if text.startswith(' ') or text.endswith(' '):
        text_node.set(XML + 'space', 'preserve')
    text_node.text = text


def set_text(paragraph, text):
    clear_runs(paragraph)
    add_text_run(paragraph, text)


def set_note(paragraph):
    clear_runs(paragraph)
    add_text_run(paragraph, '«Сегодня после седьмого колокола, кабинет 2-14. ')
    add_text_run(paragraph, 'Одна.', underline=True)
    add_text_run(paragraph, 'В.»', line_break=True)


def empty_paragraph_like(paragraph):
    blank = ET.Element(W + 'p')
    # Preserve only paragraph-level spacing/style if it exists.
    ppr = paragraph.find(W + 'pPr')
    if ppr is not None:
        blank.append(deepcopy(ppr))
    return blank


def update_core_properties(data):
    root = ET.fromstring(data)
    revision = root.find(CP + 'revision')
    if revision is not None:
        try:
            revision.text = str(int(revision.text or '0') + 1)
        except ValueError:
            pass
    modified = root.find(DCTERMS + 'modified')
    if modified is not None:
        modified.text = datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace('+00:00', 'Z')
    return ET.tostring(root, encoding='utf-8', xml_declaration=True)


def main():
    source_hash = sha256(SOURCE.read_bytes()).hexdigest()
    if source_hash != SOURCE_SHA256:
        raise SystemExit(f'Unexpected source hash: {source_hash}')

    with ZipFile(SOURCE) as zin:
        package = {info.filename: (info, zin.read(info.filename)) for info in zin.infolist()}

    root = ET.fromstring(package['word/document.xml'][1])
    body = root.find(W + 'body')
    if body is None:
        raise SystemExit('DOCX body not found')
    paragraphs = [node for node in list(body) if node.tag == W + 'p']
    if len(paragraphs) != 833 or any(not paragraph_text(p).strip() for p in paragraphs):
        raise SystemExit(f'Expected 833 non-empty paragraphs, got {len(paragraphs)}')

    for index, paragraph in enumerate(paragraphs, 1):
        if index in BLANK_BEFORE:
            body.insert(list(body).index(paragraph), empty_paragraph_like(paragraph))

        if index == 806:
            set_note(paragraph)
            continue

        if index not in EDITS:
            continue
        replacement = EDITS[index]
        if replacement is None:
            body.remove(paragraph)
            continue
        if isinstance(replacement, list):
            set_text(paragraph, replacement[0])
            anchor_pos = list(body).index(paragraph)
            for offset, extra in enumerate(replacement[1:], 1):
                clone = deepcopy(paragraph)
                set_text(clone, extra)
                body.insert(anchor_pos + offset, clone)
        else:
            set_text(paragraph, replacement)

    package['word/document.xml'] = (
        package['word/document.xml'][0],
        ET.tostring(root, encoding='utf-8', xml_declaration=True),
    )
    if 'docProps/core.xml' in package:
        info, data = package['docProps/core.xml']
        package['docProps/core.xml'] = (info, update_core_properties(data))

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(OUTPUT, 'w', ZIP_DEFLATED) as zout:
        for filename, (info, data) in package.items():
            zout.writestr(info, data)

    print(OUTPUT)


if __name__ == '__main__':
    main()
